"""Generate the shared Java catalog from reviewed, exact source-label translations."""
from pathlib import Path
import json

root=Path(__file__).resolve().parent
entries=json.loads((root/'en.json').read_text(encoding='utf-8'))
assert entries and all(isinstance(k,str) and isinstance(v,str) and v for k,v in entries.items())
def quote(value):
    return json.dumps(value,ensure_ascii=False).replace('\u2028','\\u2028').replace('\u2029','\\u2029')
lines=['package ro.leo.i18n;', '// Generated by localization/generate.py; edit en.json instead.',
       'final class EnglishCatalog {', 'static void fill(java.util.Map<String,String> out){']
lines += ['out.put('+quote(k)+','+quote(v)+');' for k,v in sorted(entries.items())]
lines += ['}', '}']
(root/'EnglishCatalog.java').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated English catalog:',len(entries),'labels')
